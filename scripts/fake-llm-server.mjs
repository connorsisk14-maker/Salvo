import http from "node:http";

const host = process.env.SALVO_FAKE_LLM_HOST ?? "127.0.0.1";
const port = Number(process.env.SALVO_FAKE_LLM_PORT ?? 9797);
const fakeMode = process.env.SALVO_FAKE_LLM_MODE ?? "local";

function readBody(request) {
  return new Promise((resolve, reject) => {
    let body = "";
    request.setEncoding("utf8");
    request.on("data", (chunk) => {
      body += chunk;
    });
    request.on("end", () => resolve(body));
    request.on("error", reject);
  });
}

function json(response, statusCode, payload) {
  response.writeHead(statusCode, {
    "content-type": "application/json"
  });
  response.end(JSON.stringify(payload));
}

function runnerResponse(model) {
  return {
    id: "msg_runner",
    model,
    stop_reason: "end_turn",
    usage: {
      input_tokens: 180,
      output_tokens: 90
    },
    content: [
      {
        type: "text",
        text: JSON.stringify({
          plan_steps: [
            "Inspect the task context",
            "Write the run summary artifact",
            "Execute the required smoke test command"
          ],
          summary: "# Smoke Summary\n\nGenerated by the fake LLM server for deterministic end-to-end verification.",
          artifacts: [
            {
              path: "run-summary.md",
              content: "# Smoke Summary\n\nGenerated by the fake LLM server for deterministic end-to-end verification.",
              artifact_type: "markdown",
              label: "run-summary.md"
            }
          ],
          learnings: [
            {
              type: "note",
              title: "Fake LLM path",
              body: "The deterministic fake provider exercised the real runner, executor, and evaluation flow."
            }
          ]
        })
      }
    ]
  };
}

function plannerResponse(model, body) {
  try {
    const userMessage = Array.isArray(body.messages)
      ? body.messages.find((message) => message.role === "user")
      : null;
    const content = typeof userMessage?.content === "string"
      ? userMessage.content
      : Array.isArray(userMessage?.content)
        ? userMessage.content.map((entry) => entry.text ?? "").join("\n")
        : "";
    const parsed = JSON.parse(content);
    const contract = parsed.base_contract;

    return {
      id: "msg_planner",
      model,
      stop_reason: "end_turn",
      usage: {
        input_tokens: 120,
        output_tokens: 75
      },
      content: [
        {
          type: "text",
          text: JSON.stringify(contract)
        }
      ]
    };
  } catch (error) {
    return {
      id: "msg_planner_fallback",
      model,
      stop_reason: "end_turn",
      usage: {
        input_tokens: 10,
        output_tokens: 10
      },
      content: [
        {
          type: "text",
          text: JSON.stringify({
            error: (error instanceof Error ? error.message : "failed to parse planner payload")
          })
        }
      ]
    };
  }
}

const server = http.createServer(async (request, response) => {
  if (request.method === "GET" && request.url === "/health") {
    return json(response, 200, { status: "ok" });
  }

  if (request.method !== "POST" || request.url !== "/v1/messages") {
    return json(response, 404, { error: "Not found" });
  }

  const rawBody = await readBody(request);
  const body = rawBody ? JSON.parse(rawBody) : {};
  const model = typeof body.model === "string" ? body.model : "claude-3-5-sonnet-latest";
  const payload = Array.isArray(body.tools) && body.tools.length > 0
    ? runnerResponse(model)
    : plannerResponse(model, body);

  return json(response, 200, payload);
});

server.listen(port, host, () => {
  console.log(`[fake-llm] mode=${fakeMode} listening on http://${host}:${port}`);
});

function shutdown() {
  server.close(() => {
    process.exit(0);
  });
}

process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
